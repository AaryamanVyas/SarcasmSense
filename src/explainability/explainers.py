"""LIME, SHAP and occlusion explainers over the trained classifier.

All three perturb the **target utterance only**, holding the conversational
context and the retrieved evidence fixed. That is a deliberate choice: it makes
the attribution answer "which words of this utterance drove the decision, given
the situation and the evidence that were actually present", rather than mixing
in the second-order effect of perturbations changing what the retriever returns.
Context and evidence influence are reported separately, straight from the
cross-attention weights.

Cost, measured in forward passes of the classifier:

===========  =========================  =============================
Method       Forward passes             Where it is used
===========  =========================  =============================
occlusion    ``1 + n_tokens``           default fast path, always works
LIME         ``num_samples`` (~200)     interactive default
SHAP         ``max_evals`` (~2n+64)     audit mode / research sampling
===========  =========================  =============================

SHAP is the most principled (Shapley values have uniqueness guarantees) and the
most expensive, which is exactly why the project runs it in a separate audit
mode rather than on every web request.
"""

from __future__ import annotations

import logging
import re
import time
from typing import Any, Sequence

import numpy as np

from src.explainability.base import (
    BaseExplainer,
    ExplanationResult,
    TokenAttribution,
    normalise_weights,
)
from src.inference.predictor import SarcasmPredictor

logger = logging.getLogger(__name__)

_WORD_RE = re.compile(r"\S+")


def _tokenise(text: str) -> list[tuple[str, int, int]]:
    """Whitespace tokenisation with character spans.

    Whitespace tokens (rather than sub-words) are what an explanation shows a
    human: "the model keyed on *great* and *perfect*" is useful; "the model keyed
    on ``Ġgre``, ``at``" is not.
    """
    return [(m.group(0), m.start(), m.end()) for m in _WORD_RE.finditer(text)]


class OcclusionExplainer(BaseExplainer):
    """Leave-one-token-out attribution.

    For each token, the utterance is re-scored with that token removed; the drop
    in the predicted class probability is its importance. Exact, deterministic,
    dependency-free and linear in the number of tokens -- which makes it both the
    fast interactive default and the guaranteed fallback when LIME or SHAP are
    unavailable.
    """

    method = "occlusion"

    def __init__(self, predictor: SarcasmPredictor, max_tokens: int = 60) -> None:
        self.predictor = predictor
        self.max_tokens = max_tokens

    @property
    def available(self) -> bool:  # noqa: D102
        return True

    def explain(
        self,
        text: str,
        context: Sequence[str] | None = None,
        retrieval: Any = None,
        num_features: int = 10,
    ) -> ExplanationResult:  # noqa: D102
        started = time.perf_counter()
        tokens = _tokenise(text)[: self.max_tokens]
        if not tokens:
            return ExplanationResult(
                method=self.method,
                warnings=["Utterance contains no tokens to attribute."],
            )
        variants = [text]
        for _, start, end in tokens:
            variants.append((text[:start] + text[end:]).strip() or ".")

        probabilities = self.predictor.predict_proba(
            variants, context=context, retrieval=retrieval
        )
        baseline = probabilities[0]
        predicted = int(baseline.argmax())
        drops = baseline[predicted] - probabilities[1:, predicted]

        attributions = [
            TokenAttribution(token=token, weight=float(drop), position=index)
            for index, ((token, _s, _e), drop) in enumerate(zip(tokens, drops))
        ]
        return ExplanationResult(
            method=self.method,
            tokens=normalise_weights(attributions)[: max(num_features, len(attributions))],
            predicted_label=predicted,
            latency_ms=(time.perf_counter() - started) * 1000,
            metadata={"forward_passes": len(variants), "exact": True},
        )


class LimeExplainer(BaseExplainer):
    """LIME (Ribeiro et al., 2016) over whitespace tokens.

    LIME fits a sparse linear surrogate to the classifier's behaviour in the
    neighbourhood of this one utterance, generated by randomly deleting subsets
    of its words. The surrogate's coefficients are the attributions.

    A fixed ``random_state`` makes the sampling reproducible, which matters --
    LIME is stochastic and an unseeded run gives visibly different weights each
    time, which would be indefensible in a viva.
    """

    method = "lime"

    def __init__(
        self,
        predictor: SarcasmPredictor,
        num_samples: int = 200,
        random_state: int = 42,
    ) -> None:
        self.predictor = predictor
        self.num_samples = num_samples
        self.random_state = random_state
        self._explainer = None
        self._error: str | None = None
        try:
            from lime.lime_text import LimeTextExplainer

            self._explainer = LimeTextExplainer(
                class_names=["Not Sarcastic", "Sarcastic"],
                random_state=random_state,
                bow=False,  # position-aware: "great" early vs late are distinct
                split_expression=r"\s+",
            )
        except ImportError as exc:  # pragma: no cover
            self._error = f"lime is not installed ({exc})"
            logger.warning("LIME unavailable: %s", self._error)

    @property
    def available(self) -> bool:  # noqa: D102
        return self._explainer is not None

    def explain(
        self,
        text: str,
        context: Sequence[str] | None = None,
        retrieval: Any = None,
        num_features: int = 10,
    ) -> ExplanationResult:  # noqa: D102
        if self._explainer is None:
            return ExplanationResult(
                method=self.method,
                available=False,
                warnings=[f"LIME explanation unavailable: {self._error}"],
            )
        started = time.perf_counter()
        tokens = _tokenise(text)
        if not tokens:
            return ExplanationResult(
                method=self.method, warnings=["Utterance contains no tokens to attribute."]
            )

        def classifier(variants: list[str]) -> np.ndarray:
            return self.predictor.predict_proba(
                variants, context=context, retrieval=retrieval
            )

        baseline = classifier([text])[0]
        predicted = int(baseline.argmax())
        try:
            explanation = self._explainer.explain_instance(
                text,
                classifier,
                labels=(predicted,),
                num_features=max(num_features, min(len(tokens), 20)),
                num_samples=self.num_samples,
            )
            pairs = explanation.as_list(label=predicted)
        except Exception as exc:  # noqa: BLE001 - never break a request
            logger.exception("LIME failed")
            return ExplanationResult(
                method=self.method,
                available=False,
                warnings=[f"LIME explanation failed ({type(exc).__name__}: {exc})"],
            )

        positions = {token: index for index, (token, _s, _e) in enumerate(tokens)}
        attributions = [
            TokenAttribution(token=token, weight=float(weight), position=positions.get(token, -1))
            for token, weight in pairs
        ]
        return ExplanationResult(
            method=self.method,
            tokens=normalise_weights(attributions),
            predicted_label=predicted,
            latency_ms=(time.perf_counter() - started) * 1000,
            metadata={
                "num_samples": self.num_samples,
                "random_state": self.random_state,
                "surrogate": "sparse linear (ridge)",
            },
        )


class ShapExplainer(BaseExplainer):
    """SHAP Partition explainer over whitespace tokens (audit mode).

    Uses :class:`shap.maskers.Text` with a whitespace split and SHAP's Partition
    algorithm, which computes Owen values -- a hierarchical approximation to
    Shapley values that is tractable for text while keeping the additivity
    property. ``max_evals`` bounds the cost.
    """

    method = "shap"

    def __init__(self, predictor: SarcasmPredictor, max_evals: int = 200) -> None:
        self.predictor = predictor
        self.max_evals = max_evals
        self._shap = None
        self._error: str | None = None
        try:
            import shap

            self._shap = shap
        except ImportError as exc:  # pragma: no cover
            self._error = f"shap is not installed ({exc})"
            logger.warning("SHAP unavailable: %s", self._error)

    @property
    def available(self) -> bool:  # noqa: D102
        return self._shap is not None

    def explain(
        self,
        text: str,
        context: Sequence[str] | None = None,
        retrieval: Any = None,
        num_features: int = 10,
    ) -> ExplanationResult:  # noqa: D102
        if self._shap is None:
            return ExplanationResult(
                method=self.method,
                available=False,
                warnings=[f"SHAP explanation unavailable: {self._error}"],
            )
        started = time.perf_counter()
        tokens = _tokenise(text)
        if not tokens:
            return ExplanationResult(
                method=self.method, warnings=["Utterance contains no tokens to attribute."]
            )
        whitespace_tokens = text.split()
        if len(whitespace_tokens) < 2:
            return ExplanationResult(
                method=self.method,
                available=False,
                warnings=[
                    "SHAP needs at least two whitespace-separated tokens to build "
                    f"a partition tree; got {len(whitespace_tokens)}."
                ],
            )
        def classifier(variants: Any) -> np.ndarray:
            return self.predictor.predict_proba(
                [str(v) for v in variants], context=context, retrieval=retrieval
            )

        baseline = classifier([text])[0]
        predicted = int(baseline.argmax())
        # Partition SHAP needs at least 2 * n_tokens + 1 evaluations to cover the
        # hierarchy; give it that much even when the caller asked for less.
        budget = max(self.max_evals, 2 * len(tokens) + 1)
        try:
            masker = self._shap.maskers.Text(r"\s+")
            explainer = self._shap.Explainer(classifier, masker, silent=True)
            values = explainer([text], max_evals=budget, silent=True)
            raw = np.asarray(values.values[0])
            words = list(values.data[0])
        except Exception as exc:  # noqa: BLE001
            logger.exception("SHAP failed")
            return ExplanationResult(
                method=self.method,
                available=False,
                warnings=[f"SHAP explanation failed ({type(exc).__name__}: {exc})"],
            )

        # raw is [n_tokens, n_classes]; take the predicted class column.
        column = raw[:, predicted] if raw.ndim == 2 else raw
        attributions = [
            TokenAttribution(token=str(word).strip(), weight=float(weight), position=index)
            for index, (word, weight) in enumerate(zip(words, column))
            if str(word).strip()
        ]
        return ExplanationResult(
            method=self.method,
            tokens=normalise_weights(attributions),
            predicted_label=predicted,
            latency_ms=(time.perf_counter() - started) * 1000,
            metadata={
                "max_evals": budget,
                "algorithm": "partition (Owen values)",
                "base_value": float(np.asarray(values.base_values[0]).ravel()[predicted])
                if getattr(values, "base_values", None) is not None
                else None,
            },
        )


class ExplainerRegistry:
    """Lazily-constructed explainers with an honest fallback chain.

    If the requested method is unavailable (library missing or a runtime
    failure), the registry falls back to :class:`OcclusionExplainer` and records
    a warning explaining the substitution. It never silently claims to have run
    SHAP when it ran something else -- :attr:`ExplanationResult.method` always
    names what actually executed.
    """

    def __init__(
        self,
        predictor: SarcasmPredictor,
        lime_num_samples: int = 200,
        shap_max_evals: int = 200,
    ) -> None:
        self.predictor = predictor
        self._explainers: dict[str, BaseExplainer] = {
            "occlusion": OcclusionExplainer(predictor),
            "lime": LimeExplainer(predictor, num_samples=lime_num_samples),
            "shap": ShapExplainer(predictor, max_evals=shap_max_evals),
        }

    def availability(self) -> dict[str, bool]:
        """Which methods can currently run."""
        return {name: explainer.available for name, explainer in self._explainers.items()}

    def explain(
        self,
        method: str,
        text: str,
        context: Sequence[str] | None = None,
        retrieval: Any = None,
        num_features: int = 10,
    ) -> ExplanationResult:
        """Explain with ``method``, falling back to occlusion when necessary."""
        method = (method or "lime").lower()
        explainer = self._explainers.get(method)
        if explainer is None:
            fallback = self._explainers["occlusion"]
            result = fallback.explain(text, context, retrieval, num_features)
            result.warnings.append(
                f"Unknown explanation method {method!r}; used {fallback.method} instead."
            )
            return result

        result = explainer.explain(text, context, retrieval, num_features)
        if result.available and result.tokens:
            return result

        fallback = self._explainers["occlusion"]
        if explainer is fallback:
            return result
        note = (
            f"{method.upper()} was requested but could not run "
            f"({'; '.join(result.warnings) or 'no attributions produced'}). "
            f"Fell back to exact occlusion attribution."
        )
        fallback_result = fallback.explain(text, context, retrieval, num_features)
        fallback_result.warnings.append(note)
        fallback_result.metadata["requested_method"] = method
        return fallback_result
